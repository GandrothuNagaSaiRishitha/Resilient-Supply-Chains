function alternativesFromReasons(
  reasons: Record<RecoveryStrategyKey, string>,
): AlternativeStrategyContext[] {
  return (Object.entries(reasons) as [RecoveryStrategyKey, string][])
    .filter(([, whyLessSuitable]) => whyLessSuitable.length > 0)
    .map(([strategyKey, whyLessSuitable]) => ({
      strategyKey,
      whyLessSuitable,
    }))
}

